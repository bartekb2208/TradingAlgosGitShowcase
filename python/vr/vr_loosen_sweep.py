"""vr_loosen_sweep.py — is the edge a REGIME or a MOMENT?

DECLARED IN ADVANCE (2026-08-04), before running:

The controls showed the signal identifies a favourable multi-hour regime
(30.8% -> 79.2% profitable within +/-30 min) while the precise trigger is
unproven (p=0.074, n=6). If that reading is right, LOOSENING the FSM should
raise structure count WITHOUT degrading per-structure forward move. If instead
quality collapses as count rises, the precision was doing real work.

THIS IS NOT "loosen until events appear". That is what F1 forbids and the
distinction only holds because:
  * the hypothesis (regime > moment) was generated by the controls, not by a
    desire for more trades;
  * the PASS/FAIL criterion is stated below before any level is run;
  * NQ -- which the loosened detector has never seen -- is the arbiter.

CRITERION: a looser level is "better" only if it raises structures/session AND
holds mean forward move >= 70% of the tight level's, ON BOTH ES AND NQ. Anything
that raises count while degrading quality is rejected.

Measured offline (detector + forward moves), so no engine is needed: this asks
whether the SIGNAL survives loosening, not what the P&L is.

NOT FINANCIAL ADVICE. Research only.
"""
from __future__ import annotations

import json
import sys
from dataclasses import replace
from datetime import datetime, timezone

import numpy as np

import vr_data as vd
from vr_core import VRConfig
from vr_detect import detect_session, forward_bps

ES = [s for s in vd.EXPLORATORY if s != "2026-07-10"]      # crossed-book exclusion
NQ = ["2026-04-06", "2026-04-07", "2026-04-08", "2026-04-09", "2026-04-10",
      "2026-04-13", "2026-04-14", "2026-04-15", "2026-04-16", "2026-04-17",
      "2026-04-20", "2026-04-21", "2026-04-22", "2026-04-23", "2026-04-24",
      "2026-04-27", "2026-04-28", "2026-04-29", "2026-04-30", "2026-05-01",
      "2026-05-04", "2026-05-05", "2026-05-06"]
NQ_SCALE = dict(cons_max_ticks=26, thin_min_ticks=26, trap_levels=16)   # price-scaled
OUT = vd.ROOT / "research" / "v-reversal" / "artifacts" / "runs" / "A5_loosen_sweep"
QUALITY_FLOOR = 0.70

LEVELS = {
    "L0_tight (current)": {},
    "L1_mild": dict(retrace_pct=0.75, trap_pctile=0.97, blowoff_mult=2.5),
    "L2_medium": dict(retrace_pct=0.60, trap_pctile=0.95, blowoff_mult=2.0,
                      cons_min_secs=45.0),
    "L3_loose": dict(retrace_pct=0.50, trap_pctile=0.90, blowoff_mult=1.5,
                     cons_min_secs=30.0, thin_min_ticks=5),
}


def measure(symbol, sessions, base_over, level_over, horizon=30.0):
    cfg = VRConfig(**{**base_over, **level_over})
    n, fwd = 0, []
    for s in sessions:
        ev = detect_session(symbol, s, cfg)
        if ev:
            _, depth = vd.load_l2(symbol, s)
            fwd.extend(forward_bps(depth, e["ts"], horizon) for e in ev)
        n += len(ev)
    a = np.array(fwd) if n else np.array([])
    return dict(structures=n, rate=n / len(sessions),
                fwd_mean_bps=float(a.mean()) if n else None,
                fwd_median_bps=float(np.median(a)) if n else None,
                pct_up=float(100 * (a > 0).mean()) if n else None)


def main() -> int:
    res = {}
    for name, over in LEVELS.items():
        e = measure("ES", ES, {}, over)
        print(f"  {name:20s} ES done: {e['structures']} structures", flush=True)
        q = measure("NQ", NQ, NQ_SCALE, over)
        print(f"  {name:20s} NQ done: {q['structures']} structures", flush=True)
        res[name] = {"ES": e, "NQ": q}

    base = res["L0_tight (current)"]
    L = ["=" * 96,
         "  VR LOOSENING SWEEP — does quality survive as structure count rises?",
         f"  ES {len(ES)} sessions (07-10 excluded, crossed book) | NQ {len(NQ)} sessions "
         f"(price-scaled, never tuned on)",
         "=" * 96,
         f"{'level':>20} | {'ES n':>5} {'ES/sess':>8} {'ES bps':>8} {'ES %up':>7} "
         f"| {'NQ n':>5} {'NQ/sess':>8} {'NQ bps':>8} {'NQ %up':>7} | {'verdict':>9}",
         "-" * 96]
    for name, r in res.items():
        e, q = r["ES"], r["NQ"]
        ok = "baseline"
        if name != "L0_tight (current)":
            be, bq = base["ES"]["fwd_mean_bps"], base["NQ"]["fwd_mean_bps"]
            more = e["rate"] > base["ES"]["rate"]
            keep_e = be is None or (e["fwd_mean_bps"] or -9) >= QUALITY_FLOOR * be
            keep_q = bq is None or (q["fwd_mean_bps"] or -9) >= QUALITY_FLOOR * bq
            ok = "ACCEPT" if (more and keep_e and keep_q) else "reject"
        L.append(f"{name:>20} | {e['structures']:5d} {e['rate']:8.2f} "
                 f"{(e['fwd_mean_bps'] or 0):8.3f} {(e['pct_up'] or 0):6.1f}% "
                 f"| {q['structures']:5d} {q['rate']:8.2f} "
                 f"{(q['fwd_mean_bps'] or 0):8.3f} {(q['pct_up'] or 0):6.1f}% | {ok:>9}")
    L += ["=" * 96,
          f"  CRITERION (declared before the run): ACCEPT only if structures/session rises",
          f"  AND mean forward move stays >= {QUALITY_FLOOR:.0%} of the tight level's, ON BOTH ES AND NQ.",
          "  NQ is the arbiter — the loosened detector has never seen it.",
          "  Forward move is in BPS: raw ticks are not comparable across ES and NQ.",
          "=" * 96]
    txt = "\n".join(L)
    print("\n" + txt)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "report.txt").write_text(txt + "\n")
    (OUT / "stats.json").write_text(json.dumps(
        {"generated_utc": datetime.now(timezone.utc).isoformat(),
         "criterion": f"rate up AND fwd_mean_bps >= {QUALITY_FLOOR} x tight, on BOTH ES and NQ",
         "es_sessions": ES, "nq_sessions": NQ, "levels": LEVELS, "results": res},
        indent=2, default=str))
    print(f"\nartifacts -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
